(FIG_DIR / "TABLE_3_adapt.tex").write_text("\n".join(t3))

# ---------------- Table 4: appendix per-seed per-family -------------------
seeds = ["20261001", "20261002", "20261003"]
def metric_of(prim, res):
    return {"choice": res.get("accuracy"), "noul": res.get("auroc"),
            "score": res.get("spearman"), "multi_noul": res.get("macro_f1")}[prim]

def per_family_agg(kind, seed):
    """kind: s1 -> per-family eval dirs; s2 -> whole-run eval_results.json"""
    acc = defaultdict(list)
    if kind == "s1":
        import glob
        for dd in sorted((AE).glob(f"s1_{seed}_*/eval_results.json")):
            for tid, r in load(dd)["results"].items():
                if "skip_reasons" in r and r.get("n", 0):
                    prim = r["primitive"]
                    m = metric_of(prim, r)
                    if m is not None:
                        acc[(family_of(tid), prim)].append(m)
    else:
        ev = load(TR / f"s2_{seed}" / "eval_results.json")["results"]
        for tid, r in ev.items():
            prim = r["primitive"]
            m = metric_of(prim, r)
            if m is not None:
                acc[(family_of(tid), prim)].append(m)
    return acc

combos = defaultdict(dict)   # (fam,prim) -> {seed: mean}
for seed in seeds:
    for kind in ("s1", "s2"):
        for key, ms in per_family_agg(kind, seed).items():
            combos[key].setdefault(kind, []).append(np.mean(ms))
t4 = [r"% Table 4: appendix per-family comparison (generated by gen_tables.py; seed-avg of per-task metrics)",
      r"\begin{table}[t]", r"\centering",
      r"\caption{Per-family, per-seed means for the two trained arms (task-macro of per-task seed means). "
      r"\#1 uses per-family early-stop checkpoints (37-task slice; families as in the training scheduler), "
      r"\#2 the full-run checkpoint. DeepLoc (multi\_noul) and double-sequence tasks are outside this harness.}",
      r"\label{tab:appendix}", r"\footnotesize",
      r"\begin{tabular}{llccc}", r"\toprule",
      r"Family & Primitive & \#1 (mean$\pm$std over 3 seeds) & \#2 & n \\ \midrule"]
for (f, p) in sorted(combos):
    a1 = np.array(combos[(f, p)].get("s1", []))
    a2 = np.array(combos[(f, p)].get("s2", []))
    if len(a1) == 0 and len(a2) == 0:
        continue
    s1 = f"{a1.mean():.3f}$\\pm${a1.std():.3f}" if len(a1) else "--"
    s2 = f"{a2.mean():.3f}$\\pm${a2.std():.3f}" if len(a2) else "--"
    n = max(len(a1), len(a2))
    t4.append(esc(f) + f" & {p} & {s1} & {s2} & {n} \\\\")
t4 += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
(FIG_DIR / "TABLE_4_appendix.tex").write_text("\n".join(t4))

# ---------------- Table 5: phrasing x 3 checkpoints ------------------------
ab = load(AE / "noul_ablation_3seed.json")
PN = {"current_false_no": "false: no / true: yes", "plain_false_true": "false / true",
      "proposition": "proposition (``yes, it does'')", "raw_no_yes": "no / yes (trained)",
      "descriptive": "descriptive", "neg_pos_words": "neg / pos words"}
t5 = [r"% Table 5: noul phrasing x 3 stable checkpoints (gen_tables.py)",
      r"\begin{table}[t]", r"\centering",
      r"\caption{Noul AUROC on GB tasks for six candidate phrasings, evaluated on three "
      r"seed-averaged stable checkpoints (same weights per column; only rendered candidate "
      r"text varies). No phrasing reaches the per-task-head reference (0.629). "
      r"The trained phrasing is marked \dag.}",
      r"\label{tab:phrasing}", r"\small",
      r"\begin{tabular}{lcccc}", r"\toprule",
      r"Phrasing & s1 & s2 & s3 & mean$\pm$std \\ \midrule"]
for k, v in sorted(ab["per_phrasing"].items(), key=lambda kv: -kv[1]["mean"]):
    nm = PN[k] + (r"$^\dagger$" if k == ab["trained_phrasing"] else "")
    t5.append(nm + " & " + " & ".join(f"{x:.3f}" for x in v["per_seed"]) +
              f" & {v['mean']:.3f}$\\pm${v['std']:.3f} \\\\")
t5 += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
(FIG_DIR / "TABLE_5_phrasing.tex").write_text("\n".join(t5))

# ---------------- Table 6: TAPE cross-family 3-seed ------------------------
tp = load(AE / "cross_family_tape_3seed.json")
t6 = [r"% Table 6: TAPE cross-family score arm, 3 seeds (gen_tables.py)",
      r"\begin{table}[t]", r"\centering",
      r"\caption{Cross-family score transfer (TAPE held out; DeepSTARR and ProteinGym score "
      r"families in training). Spearman per seed; ``abs'' = trained absolute value. "
      r"Stability's positive $\Delta$ reflects a pathological frozen baseline "
      r"($-0.218$) regressing toward zero, not genuine transfer.}",
      r"\label{tab:tape}", r"\small",
      r"\begin{tabular}{llccccc}", r"\toprule",
      r"Task & & frozen & tr.\ s1 & tr.\ s2 & tr.\ s3 & $\Delta$ mean$\pm$std \\ \midrule"]
for task, d in tp["per_task"].items():
    seeds = ["s1", "s2", "s3"]
    fr = np.mean([d["per_seed"][s]["frozen"] for s in seeds])
    trs = [d["per_seed"][s]["trained"] for s in seeds]
    t6.append(task.replace("_", "\\_") + r" & abs & " + f"{fr:.3f} & " +
              " & ".join(f"{x:.3f}" for x in trs) +
              f" & {d['mean_delta']:+.3f}$\\pm${d['std_delta']:.3f} \\\\")
t6 += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
(FIG_DIR / "TABLE_6_tape.tex").write_text("\n".join(t6))
print("Wrote TABLE_1..6 tex. Table4 combos:", len(combos))
